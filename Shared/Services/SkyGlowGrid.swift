    static func cell(_ i: Int, _ j: Int) -> Double {
        let q = Double(values[i * nLon + j])
        return 0.01 * (pow(10, q / 40) - 1)
    }

    /// Bilinearly interpolated index, nil outside the grid.
    static func index(at c: Coordinate) -> Double? {
        let y = (c.lat - lat0) / dLat, x = (c.lon - lon0) / dLon
        guard values.count == nLat * nLon, y >= 0, x >= 0, y <= Double(nLat - 1), x <= Double(nLon - 1) else { return nil }
        let i = min(Int(y), nLat - 2), j = min(Int(x), nLon - 2)
        let fy = y - Double(i), fx = x - Double(j)
        let top = cell(i, j) * (1 - fx) + cell(i, j + 1) * fx
        let bottom = cell(i + 1, j) * (1 - fx) + cell(i + 1, j + 1) * fx
        return top * (1 - fy) + bottom * fy
    }
